package src.Basics.Operators;

public class RelationalOperators {
    public static void main(String[] args) {
        // > greaterthan
        // < lessthan
        // == equals
        // != not equals
        // >= greaterthan or equals
        // <= lessthan or equals
        int a=10;
        int b=20;
        float c=20.0f;
        System.out.println(a>b);
        System.out.println(a<b);
        System.out.println(a==b);
        System.out.println(a!=b);
        System.out.println(a>=b);
        System.out.println(a<=b);
        System.out.println(b==c);
    }
}
